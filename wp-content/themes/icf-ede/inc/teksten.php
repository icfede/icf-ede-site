	function icf_patroon_taal() {
		if ( ! empty( $GLOBALS['icf_lang'] ) ) {
			return $GLOBALS['icf_lang'];
		}
		if ( function_exists( 'pll_current_language' ) && pll_current_language() ) {
			return pll_current_language();
		}
		return 'nl';
	}

	function icf_pt( $key ) {
		static $t = null;
		if ( null === $t ) {
			$t = icf_patroon_teksten();
		}
		$lang = icf_patroon_taal();
		if ( isset( $t[ $lang ][ $key ] ) ) {
			return $t[ $lang ][ $key ];
		}
		return isset( $t['nl'][ $key ] ) ? $t['nl'][ $key ] : $key;
	}

